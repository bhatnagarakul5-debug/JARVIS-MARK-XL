"""
actions/file_generator.py — Universal Multi-Format Document Authoring Engine for JARVIS Mark 58
Empowers JARVIS to generate all kinds of files on demand:
- Word Documents (.docx) with formatted headings, styled tables, and bullet points.
- PowerPoint Presentations (.pptx) with modern slide layouts, cards, and speaker notes.
- PDF Documents (.pdf) with clean typography, tables, and revision cheat sheets using ReportLab.
- Excel Spreadsheets (.xlsx, .csv) with headers, formulas, and auto-sized columns using OpenPyXL.
- Code & Text Files (.py, .md, .txt, .html, .tex, .json).
"""

import os
import sys
